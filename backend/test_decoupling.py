FORBIDDEN_UI_PATTERNS = [
    re.compile(r"\b(bg-[a-z]+-\d+|text-[a-z]+-\d+|border-[a-z]+-\d+)\b"),
    re.compile(r"#(?:[0-9a-fA-F]{3}){1,2}\b"),
]

def test_high_fives_routes_removed_from_app():
    """Verify that no high-fives routes are mounted in the FastAPI application."""
    all_routes = [route.path for route in app.routes]
    forbidden_routes = [
        "/send-high-five",
        "/parent/send-high-five",
        "/api/v1/aurastudy/parent/send-high-five",
        "/high-fives",
        "/parent/high-fives",
        "/api/v1/aurastudy/parent/high-fives",
        "/ack-high-five/{high_five_id}",
        "/parent/ack-high-five/{high_five_id}",
    ]
    for r in forbidden_routes:
        assert r not in all_routes, f"Forbidden route still exists in app.routes: {r}"
    print("[PASS] High-Fives routes successfully eliminated from application routes.")

def test_high_fives_models_removed():
    """Verify that High-Fives models do not exist in app.parent.models."""
