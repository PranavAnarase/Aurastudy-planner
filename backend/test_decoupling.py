def test_openapi_schema_cleanliness():
    """Verify OpenAPI schema generated by FastAPI contains no high-fives schemas or endpoints."""
    schema = app.openapi()
    paths = schema.get("paths", {})
    schemas = schema.get("components", {}).get("schemas", {})

    for p in paths:
        assert "high-five" not in p, f"High-five path leaked into OpenAPI: {p}"

    assert "SendHighFiveRequest" not in schemas, "SendHighFiveRequest found in OpenAPI schemas"
    assert "HighFiveItem" not in schemas, "HighFiveItem found in OpenAPI schemas"

    subject_schema = schemas.get("SubjectMasteryCard", {}).get("properties", {})
    assert "subject_category" in subject_schema, "subject_category missing from SubjectMasteryCard schema"

    print("[PASS] OpenAPI schema is clean, valid, and contains zero high-fives artifacts.")

